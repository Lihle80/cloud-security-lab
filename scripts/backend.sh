#!/usr/bin/env bash
#
# Generates backend.hcl for the numbered stacks.
#
# The state bucket name contains the account ID, which is why it is not
# committed: a public portfolio repo should not advertise an account
# number. This derives it at run time instead.
#
# Usage:
#   ./scripts/backend.sh                 # write ./backend.hcl
#   ./scripts/backend.sh && terraform -chdir=stacks/10-org \
#       init -backend-config=../../backend.hcl
#
set -euo pipefail

REGION="${AWS_REGION:-us-west-2}"
PROJECT="${PROJECT:-aws-security-lab}"

ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
BUCKET="${PROJECT}-tfstate-${ACCOUNT_ID}"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${REPO_ROOT}/backend.hcl"

if ! aws s3api head-bucket --bucket "$BUCKET" 2>/dev/null; then
  echo "ERROR: state bucket $BUCKET does not exist." >&2
  echo "       Apply stacks/00-bootstrap first — it uses local state and" >&2
  echo "       creates this bucket." >&2
  exit 1
fi

cat > "$OUT" <<EOF
# Generated by scripts/backend.sh — do not commit.
bucket = "${BUCKET}"
region = "${REGION}"
EOF

echo "wrote $OUT"
echo "  bucket = $BUCKET"
echo "  region = $REGION"
echo
echo "Initialise a stack with:"
echo "  terraform -chdir=stacks/10-org init -backend-config=\"$OUT\""
